import { config } from '../config/index.js';

export interface FallbackContextItem {
  tool: string;
  args: Record<string, any>;
  result: any;
}

export class HuggingFaceFallbackClient {
  private apiKey: string;
  private model: string;
  private baseUrl: string;

  constructor(apiKey?: string, model?: string, baseUrl?: string) {
    this.apiKey = apiKey || config.huggingFaceApiKey;
    this.model = model || config.huggingFaceModel;
    this.baseUrl = baseUrl || config.huggingFaceBaseUrl;
  }

  isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.trim().length > 0);
  }

  async generateResponse(params: {
    prompt: string;
    verifiedContext: FallbackContextItem[];
    systemInstruction?: string;
  }): Promise<{ reply: string; model: string; provider: 'huggingface' }> {
    if (!this.isConfigured()) {
      throw new Error(
        'Hugging Face fallback is not configured. Please specify HUGGINGFACE_API_KEY in your environment.'
      );
    }

    const defaultSystem =
      'You are SubPilot, an enterprise billing AI assistant for Brightloop Software Subscription Management System (SMS). ' +
      'Answer user billing questions accurately based ONLY on the verified business records provided in the context. ' +
      'Preserve exact decimal string monetary figures (e.g. "45000.00", "10000.00") and currency codes (e.g. INR) verbatim. ' +
      'Never divide amounts by 100. Never convert to floats. Do not fabricate or hallucinate financial transactions, invoice numbers, or customer names.';

    const contextSummary = params.verifiedContext.length > 0
      ? params.verifiedContext
          .map((c) => `[Tool: ${c.tool}]\nParameters: ${JSON.stringify(c.args)}\nResult:\n${JSON.stringify(c.result, null, 2)}`)
          .join('\n\n')
      : 'No verified business records were retrieved for this query.';

    const systemPrompt = `${params.systemInstruction || defaultSystem}\n\n### VERIFIED BUSINESS CONTEXT:\n${contextSummary}`;

    const headers: Record<string, string> = {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${this.apiKey.trim()}`
    };

    // Support both router /chat/completions and classic model inference endpoint
    const url = this.baseUrl.includes('chat/completions')
      ? this.baseUrl
      : `${this.baseUrl.replace(/\/+$/, '')}/${this.model}/v1/chat/completions`;

    try {
      const response = await fetch(url, {
        method: 'POST',
        headers,
        body: JSON.stringify({
          model: this.model,
          messages: [
            { role: 'system', content: systemPrompt },
            { role: 'user', content: params.prompt }
          ],
          temperature: 0.1,
          max_tokens: 1024
        })
      });

      if (!response.ok) {
        // Fallback to classic pipeline endpoint if v1/chat/completions returned 404
        if (response.status === 404) {
          const directUrl = `${this.baseUrl.replace(/\/+$/, '')}/${this.model}`;
          const directRes = await fetch(directUrl, {
            method: 'POST',
            headers,
            body: JSON.stringify({
              inputs: `<s>[INST] <<SYS>>\n${systemPrompt}\n<</SYS>>\n\n${params.prompt} [/INST]`,
              parameters: { max_new_tokens: 1024, temperature: 0.1 }
            })
          });

          if (!directRes.ok) {
            const errText = await directRes.text();
            throw new Error(`Hugging Face API returned HTTP ${directRes.status}: ${errText}`);
          }

          const directJson: any = await directRes.json();
          const generatedText = Array.isArray(directJson)
            ? directJson[0]?.generated_text || JSON.stringify(directJson)
            : directJson?.generated_text || JSON.stringify(directJson);

          return {
            reply: generatedText,
            model: this.model,
            provider: 'huggingface'
          };
        }

        const errorBody = await response.text();
        throw new Error(`Hugging Face API error (status ${response.status}): ${errorBody}`);
      }

      const completion: any = await response.json();
      const reply = completion.choices?.[0]?.message?.content || 'No response generated by fallback model';

      return {
        reply,
        model: this.model,
        provider: 'huggingface'
      };
    } catch (err: any) {
      throw new Error(`Hugging Face fallback failed: ${err.message}`);
    }
  }
}
